import {
  AlertCircle,
  CheckCircle2,
  Loader2,
  Save,
  Stethoscope,
} from "lucide-react";
import { useMemo, useState } from "react";

import { createPrediction } from "../services/api";
import { getCurrentUserToken } from "../services/auth";
import type { PredictionInput, PredictionResult } from "../types/prediction";
import { predictionFields } from "../utils/predictionFields";

const initialFormState: PredictionInput = {
  patient_name: "",
  age: 58,
  sex: 1,
  cp: 4,
  trestbps: 140,
  chol: 250,
  fbs: 0,
  restecg: 2,
  thalach: 120,
  exang: 1,
  oldpeak: 2,
  slope: 2,
  ca: 1,
  thal: 7,
};

export function NewPredictionPage() {
  const [formData, setFormData] = useState<PredictionInput>(initialFormState);
  const [result, setResult] = useState<PredictionResult | null>(null);
  const [errorMessage, setErrorMessage] = useState("");
  const [isSubmitting, setIsSubmitting] = useState(false);

  const requiredFieldsCompleted = useMemo(
    () =>
      predictionFields
        .filter((field) => field.name !== "patient_name")
        .every(
          (field) =>
            formData[field.name] !== undefined && formData[field.name] !== "",
        ),
    [formData],
  );

  function updateField(name: keyof PredictionInput, value: string) {
    setFormData((current) => ({
      ...current,
      [name]: name === "patient_name" ? value : Number(value),
    }));
  }

  async function handleSubmit(event: React.FormEvent<HTMLFormElement>) {
    event.preventDefault();
    setErrorMessage("");
    setResult(null);
    setIsSubmitting(true);

    try {
      const token = await getCurrentUserToken();

      if (!token) {
        throw new Error("Please sign in before saving a prediction.");
      }

      const response = await createPrediction(formData, token);
      setResult(response.result);
    } catch (error) {
      setErrorMessage(
        error instanceof Error ? error.message : "Prediction failed.",
      );
    } finally {
      setIsSubmitting(false);
    }
  }

  return (
    <div className="space-y-6">
      <div>
        <p className="text-sm font-medium text-rose-700">New Prediction</p>
        <h1 className="text-2xl font-bold text-slate-950">
          Patient risk assessment
        </h1>
        <p className="mt-1 max-w-2xl text-sm text-slate-600">
          Enter clinical values from the Cleveland heart disease feature set to
          create a prediction.
        </p>
      </div>

      <form
        onSubmit={handleSubmit}
        className="rounded-lg border border-slate-200 bg-white p-5 shadow-sm"
      >
        <div className="flex items-center gap-3 border-b border-slate-100 pb-4">
          <div className="flex size-10 items-center justify-center rounded-md bg-rose-50 text-rose-700">
            <Stethoscope size={20} />
          </div>
          <div>
            <h2 className="text-base font-semibold text-slate-950">
              Clinical Inputs
            </h2>
            <p className="text-sm text-slate-500">
              All numeric fields are required.
            </p>
          </div>
        </div>

        <div className="mt-5 grid gap-4 md:grid-cols-2 xl:grid-cols-3">
          {predictionFields.map((field) => (
            <label key={field.name} className="space-y-2">
              <span className="text-sm font-medium text-slate-700">
                {field.label}
              </span>
              <input
                type={field.type}
                min={field.min}
                max={field.max}
                step={field.step}
                value={formData[field.name] ?? ""}
                onChange={(event) =>
                  updateField(field.name, event.target.value)
                }
                className="h-11 w-full rounded-md border border-slate-300 bg-white px-3 text-sm outline-none transition focus:border-rose-500 focus:ring-2 focus:ring-rose-100"
              />
              {field.helper ? (
                <span className="block text-xs text-slate-500">
                  {field.helper}
                </span>
              ) : null}
            </label>
          ))}
        </div>

        <div className="mt-6 flex flex-col gap-3 border-t border-slate-100 pt-5 sm:flex-row sm:items-center sm:justify-between">
          <p className="text-sm text-slate-500">
            Results are generated by the saved machine-learning pipeline and
            stored in Firebase.
          </p>
          <button
            type="submit"
            disabled={!requiredFieldsCompleted || isSubmitting}
            className="inline-flex h-11 items-center justify-center gap-2 rounded-md bg-rose-600 px-4 text-sm font-semibold text-white transition hover:bg-rose-700 disabled:cursor-not-allowed disabled:bg-slate-300"
          >
            {isSubmitting ? (
              <Loader2 className="animate-spin" size={18} />
            ) : (
              <Save size={18} />
            )}
            Save Prediction
          </button>
        </div>
      </form>

      {errorMessage ? (
        <div className="flex items-start gap-3 rounded-lg border border-amber-200 bg-amber-50 p-4 text-amber-900">
          <AlertCircle className="mt-0.5 shrink-0" size={20} />
          <p className="text-sm font-medium">{errorMessage}</p>
        </div>
      ) : null}

      {result ? (
        <div className="rounded-lg border border-slate-200 bg-white p-5 shadow-sm">
          <div className="flex items-center gap-3">
            <CheckCircle2
              className={
                result.prediction === 1 ? "text-red-700" : "text-emerald-700"
              }
              size={22}
            />
            <div>
              <h2 className="text-base font-semibold text-slate-950">
                {result.risk_label}
              </h2>
              <p className="text-sm text-slate-500">
                Model: {result.model_name} {result.model_version}
              </p>
            </div>
          </div>

          <div className="mt-5 grid gap-4 sm:grid-cols-2">
            <div className="rounded-md bg-emerald-50 p-4">
              <p className="text-sm font-medium text-emerald-800">
                Lower-risk probability
              </p>
              <p className="mt-2 text-2xl font-bold text-emerald-900">
                {(result.lower_risk_probability * 100).toFixed(1)}%
              </p>
            </div>
            <div className="rounded-md bg-rose-50 p-4">
              <p className="text-sm font-medium text-rose-800">
                Higher-risk probability
              </p>
              <p className="mt-2 text-2xl font-bold text-rose-900">
                {(result.higher_risk_probability * 100).toFixed(1)}%
              </p>
            </div>
          </div>
        </div>
      ) : null}
    </div>
  );
}
